"""Pin dcm_qa repositories (Chris Rorden's dcm2niix validation data) for the test suite.

Writes ``tests/data/dcm_qa.json``: per repository the current commit of its default branch and
every file under ``In/`` (the DICOM input) with its git blob SHA-1 and size, which
``tests/dcmqa.py`` uses to verify downloads. Uses the GitHub REST API without authentication
(2 requests per repository).

    uv run python scripts/pin_dcm_qa.py            # re-pin the repositories listed below
"""

import json
import urllib.request
from pathlib import Path

OWNER = "neurolabusc"
#: Small repositories that cover the open phases; see docs/dev/test-data.md.
REPOSITORIES = [
    "dcm_qa_12bit",
    "dcm_qa_enh",
    "dcm_qa_me",
    "dcm_qa_nih",
    "dcm_qa_pdt2",
    "dcm_qa_philips_dwi",
    "dcm_qa_ts",
]
TARGET = Path(__file__).resolve().parent.parent / "tests" / "data" / "dcm_qa.json"


def _get(url: str):
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def pin(repository: str) -> dict:
    api = f"https://api.github.com/repos/{OWNER}/{repository}"
    branch = _get(api)["default_branch"]
    commit = _get(f"{api}/commits/{branch}")["sha"]
    tree = _get(f"{api}/git/trees/{commit}?recursive=1")
    if tree["truncated"]:
        raise RuntimeError(f"{repository}: tree listing truncated")
    files = {
        entry["path"]: {"git_sha1": entry["sha"], "size": entry["size"]}
        for entry in tree["tree"]
        if entry["type"] == "blob" and entry["path"].startswith("In/")
    }
    if not files:
        raise RuntimeError(f"{repository}: no files under In/")
    return {"commit": commit, "files": dict(sorted(files.items()))}


def main() -> None:
    manifest = {
        "owner": OWNER,
        "note": (
            "Generated by scripts/pin_dcm_qa.py. Files under In/ only; git_sha1 is the git "
            "blob hash (sha1 of 'blob <size>\\0' + content). License: BSD-2-Clause per repo."
        ),
        "repositories": {name: pin(name) for name in REPOSITORIES},
    }
    TARGET.write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    for name, repo in manifest["repositories"].items():
        size = sum(f["size"] for f in repo["files"].values()) / 2**20
        print(f"{name}: {repo['commit'][:8]}, {len(repo['files'])} files, {size:.0f} MB")


if __name__ == "__main__":
    main()
